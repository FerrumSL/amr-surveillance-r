# Check the MIC/disk interpretation against real laboratory calls.
#
# Input:  data/raw/ncbi_ast_long.csv.gz (R/00_fetch_ncbi.R): each test's raw value and the S/I/R
#         the submitting lab reported, with the testing standard it used.
# Output: reports/ncbi/validation.md, reports/ncbi/tables/validation.csv
#
# Only CLSI tests are used. Each value is interpreted twice with interpret_column() from
# R/01_clean.R: with CLSI 2025 (what the pipeline does), and with the CLSI version of the
# isolate's collection year (closest to what the lab had). Error classes follow CLSI M52:
# very major = we say S, the lab said R; major = we say R, the lab said S; minor = one side I.

suppressPackageStartupMessages({
  library(AMR)
  library(dplyr)
  library(readr)
})
withr::with_options(list(amrwf.skip_main = TRUE), source("R/01_clean.R"))

lookup <- read_csv("data/organism_lookup.csv", col_types = cols(.default = col_character()))
long <- read_csv("data/raw/ncbi_ast_long.csv.gz", col_types = cols(.default = col_character()), na = "")

tests <- long |>
  filter(standard == "CLSI", phenotype %in% c("susceptible", "intermediate", "resistant"),
         method %in% c("MIC", "disk diffusion")) |>
  mutate(ab = as.character(suppressWarnings(as.ab(antibiotic, info = FALSE))),
         method = ifelse(method == "MIC", "mic", "disk"),
         value = paste0(ifelse(sign %in% c("==", "="), "", sign), measurement),
         lab = toupper(substr(phenotype, 1, 1)),
         year = suppressWarnings(as.integer(substr(collection_date, 1, 4))),
         # Breakpoint tables in the AMR package start in 2011.
         year_guideline = ifelse(is.na(year), NA, paste("CLSI", pmin(pmax(year, 2011), 2026)))) |>
  filter(!is.na(ab), grepl("[0-9]", value))
tests$mo <- as.character(clean_organism(tests$organism, lookup)$mo)

interpret_groups <- function(data, guideline_col) {
  data |>
    group_by(ab, method, g = .data[[guideline_col]]) |>
    group_modify(function(d, key) {
      if (is.na(key$g)) return(mutate(d, sir = NA_character_))
      r <- interpret_column(d$value, as.mo(d$mo, info = FALSE), key$ab, key$method, key$g)
      mutate(d, sir = as.character(r$sir))
    }) |>
    ungroup() |>
    select(-g)
}
tests$guideline_2025 <- "CLSI 2025"
now <- interpret_groups(tests, "guideline_2025") |> rename(sir_2025 = sir)
then <- interpret_groups(tests, "year_guideline") |> select(accession, ab, method, value, sir_year = sir)
cmp <- now |>
  left_join(distinct(then, accession, ab, method, value, .keep_all = TRUE),
            by = c("accession", "ab", "method", "value"))

classify <- function(ours, lab) {
  case_when(is.na(ours) | !ours %in% c("S", "I", "R") ~ "no breakpoint",
            ours == lab ~ "agree",
            ours == "S" & lab == "R" ~ "very major",
            ours == "R" & lab == "S" ~ "major",
            TRUE ~ "minor")
}
cmp <- mutate(cmp, result_2025 = classify(sir_2025, lab), result_year = classify(sir_year, lab))

summarise_errors <- function(d, col) {
  d |>
    filter(.data[[col]] != "no breakpoint") |>
    summarise(n = n(), agree = mean(.data[[col]] == "agree"),
              very_major = sum(.data[[col]] == "very major"), major = sum(.data[[col]] == "major"),
              minor = sum(.data[[col]] == "minor"), .groups = "drop")
}
overall <- bind_rows(
  mutate(summarise_errors(cmp, "result_2025"), breakpoints = "CLSI 2025 for every test"),
  mutate(summarise_errors(filter(cmp, !is.na(year)), "result_year"), breakpoints = "CLSI of the collection year")
)
by_pair <- cmp |>
  group_by(organism = mo_shortname(mo, language = NULL), antibiotic = ab_name(ab, language = NULL)) |>
  summarise_errors("result_2025") |>
  ungroup() |>
  filter(n >= 20) |>
  arrange(agree)
dir.create("reports/ncbi/tables", showWarnings = FALSE, recursive = TRUE)
write_csv(by_pair, "reports/ncbi/tables/validation.csv")

pct <- function(x) sprintf("%.1f%%", 100 * x)
worst <- head(by_pair, 10)
lines <- c(
  "# Interpretation check against real laboratory calls",
  "",
  "Generated by `R/04_validate.R` from NCBI BioSample antibiograms (human isolates).",
  "",
  sprintf("%d CLSI MIC and disk tests from %d isolates were re-interpreted by the pipeline and compared",
          nrow(cmp), n_distinct(cmp$accession)),
  "with the S/I/R the submitting laboratory reported. Very major: pipeline S, lab R.",
  "Major: pipeline R, lab S. Minor: one of the two is I.",
  "",
  "| Breakpoints used | Tests compared | Agreement | Very major | Major | Minor |",
  "|---|---|---|---|---|---|",
  sprintf("| %s | %d | %s | %d | %d | %d |", overall$breakpoints, overall$n, pct(overall$agree),
          overall$very_major, overall$major, overall$minor),
  "",
  sprintf("Tests with no CLSI 2025 breakpoint for that organism and drug: %d (left out above).",
          sum(cmp$result_2025 == "no breakpoint")),
  "",
  "## Lowest agreement (organism and drug pairs with at least 20 tests)",
  "",
  "| Organism | Drug | Tests | Agreement | Very major | Major | Minor |",
  "|---|---|---|---|---|---|---|",
  sprintf("| %s | %s | %d | %s | %d | %d | %d |", worst$organism, worst$antibiotic, worst$n,
          pct(worst$agree), worst$very_major, worst$major, worst$minor),
  "",
  "All pairs: `reports/ncbi/tables/validation.csv`.",
  "",
  "Disagreement is not automatically a pipeline error. Breakpoints change between CLSI versions",
  "(compare the two rows of the first table), labs apply their own rules, and some submitters",
  "report a phenotype from a different method than the measurement shown."
)
writeLines(lines, "reports/ncbi/validation.md")
message("Wrote reports/ncbi/validation.md")
